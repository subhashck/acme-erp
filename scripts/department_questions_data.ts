// Keep each written topic once, preserving its original code and difficulty.
function buildPool(topics: QuestionTemplate[], deptTag: string, prefix: string): QuestionDef[] {
  return topics.map(base => makeQ(
    `MCQ-${prefix}-${String(base.number).padStart(3, "0")}`,
    base.domainCode, base.q, base.opts, base.ans, base.exp,
    [...new Set([deptTag, ...base.tags])], base.diff, 60
  ));
}

