interface QuestionTemplate {
  /** Original code suffix; gaps are deliberate after consolidation. */
  number: number;
  q: string;
  opts: [string, string, string, string];
  ans: 0 | 1 | 2 | 3;
  exp: string;
  diff: "basic" | "medium" | "advanced";
  tags: string[];
  domainCode: QuestionDef["domainCode"];
}

function makeQ(
  code: string,
  domainCode: QuestionDef["domainCode"],
  question: string,
  options: [string, string, string, string],
  correctOptionIndex: 0 | 1 | 2 | 3,
  explanation: string,
  departmentTags: string[],
  difficulty: QuestionDef["difficulty"] = "medium",
  defaultTimeSeconds: number = 60
): QuestionDef {
  return {
    code,
    domainCode,
    question,
    options,
    correctOptionIndex,
    explanation,
    departmentTags,
    difficulty,
    defaultTimeSeconds,
  };
}

